import { withPayload } from '@payloadcms/next/withPayload';
import type { NextConfig } from 'next';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dirname = path.dirname(fileURLToPath(import.meta.url));

// Headers that never depend on the route or on runtime env. Route-dependent headers (CSP,
// X-Frame-Options, X-Robots-Tag, COOP) come from src/proxy.ts. Browsers ignore HSTS on plain
// HTTP responses (RFC 6797 section 8.1, to be confirmed by the platform lane), so it is static.
const staticSecurityHeaders = [
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
  {
    key: 'Permissions-Policy',
    value: 'camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()',
  },
  { key: 'Strict-Transport-Security', value: 'max-age=63072000; includeSubDomains' },
];

const nextConfig: NextConfig = {
  output: 'standalone',
  poweredByHeader: false,
  reactStrictMode: true,
  // Trailing-slash redirects are one-hop 301s in the proxy (canonical redirect).
  skipTrailingSlashRedirect: true,
  // Metadata always in <head>: link-preview bots outside Next's default list get it too.
  htmlLimitedBots: /.*/,
  turbopack: { root: path.resolve(dirname) },
  // All server code is bundled; no file under src/ is read at run time. File tracing still
  // copies src/collections/* (tests included) into the artifact because the media file handler
  // calls fs with a computed path.
  outputFileTracingExcludes: { '/*': ['src/**'] },
  // `next dev` must not write a generated AGENTS.md into the repository.
  agentRules: false,
  experimental: {
    // Payload picks log levels and error response shapes from error class names. A minified
    // server bundle renames the classes, so every 403 and 400 logs as ERROR with a stack and
    // some API errors lose their message and field data. Client bundles stay minified.
    serverMinification: false,
  },
  // No `images` block: media sizes are generated by Payload, the runtime optimizer is not used.
  async headers() {
    return [
      { source: '/:path*', headers: staticSecurityHeaders },
      {
        source: '/brand/:path*',
        headers: [{ key: 'Cache-Control', value: 'public, max-age=604800' }],
      },
      {
        source: '/fonts/:path*',
        headers: [{ key: 'Cache-Control', value: 'public, max-age=2592000' }],
      },
    ];
  },
};

const withPayloadConfig = withPayload(nextConfig, { devBundleServerPackages: false });
const payloadHeaders = withPayloadConfig.headers;

// withPayload appends Accept-CH, Vary and Critical-CH (Sec-CH-Prefers-Color-Scheme) on
// '/:path*'. Critical-CH makes the browser retry a navigation that lacked the hint, an extra
// round trip on the first public page view. The hint only drives the admin theme: scope it.
export default {
  ...withPayloadConfig,
  headers: async () => {
    const rules = payloadHeaders ? await payloadHeaders() : [];
    return rules.map((rule) =>
      rule.source === '/:path*' && rule.headers.some((h) => h.key === 'Critical-CH')
        ? { ...rule, source: '/admin/:path*' }
        : rule,
    );
  },
} satisfies NextConfig;
